#!/usr/bin/env python3
"""Generate config/ambiguous_tickers.txt: tickers whose BARE form (no $) is a common word, so a bare-ticker
X search cannot count them honestly. Dev-only (needs `pip install wordfreq`); the output is committed and the
ranking script never imports wordfreq.

Rule (2026-10-17, bare-ticker method v4):
  - 1-2 letter tickers: always ambiguous (A, AI, BE, IT, ON, MU, ...)
  - English word frequency zipf >= 3.0 (about 1 per million words and more: ALL, NOW, CAR, OPEN, SHOP, ...)
  - or zipf >= 4.0 in de/fr/es/it/pt/nl (DIA, META in pt/es, ...)
  - plus MANUAL_EXTRA (slang/acronyms the frequency list misses), minus ALLOW (tokens frequent only BECAUSE of
    the company/ticker itself: AMD, CRM, MARA, ...).
config/context_tickers.txt then re-admits a few big core names with a required finance-context clause.
"""
import csv
import os
import sys

import wordfreq

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EN_MIN = 3.0
OTHER_MIN = 4.0
OTHER = ("de", "fr", "es", "it", "pt", "nl")
# slang / acronyms / names that are clearly not about the stock in a bare search
MANUAL_EXTRA = {"SMH", "LOL", "OMG", "WTF", "IMO", "FOMO", "YOLO", "HODL", "MOON", "PUMP", "BULL", "BEAR", "CEO",
                "USA", "NYC", "ATH", "EPS", "IPO", "ETF", "GDP", "CPI", "FED", "SEC", "FBI", "CIA", "NBA", "NFL",
                "UFC", "WWE", "TV", "PC", "UK", "EU", "LIT", "LITE", "AERO", "PILL", "DOG", "CAT", "FUN", "CAR",
                # 2026-10-17 first bare run: SOFI 3,080 bare vs 141 $SOFI the run before (name Sofi/Sofia, SoFi Stadium)
                "SOFI",
                # 2026-10-17 11:17 run (bare 5h vs median $cashtag 5h): SHOP 10,901 vs 21 (the word "shop"),
                # BABA 6,669 vs 34, MARA 1,783 vs 27, NIO 353 vs 35, CRM 296 vs 20.5, PDD 140 vs 6.5
                "SHOP", "BABA", "MARA", "NIO", "PDD", "CRM",
                # 2026-10-17 11:17 run, held by the word-collision guard (no $cashtag history): HAIN 8,028 bare,
                # HAO 1,522, HAVA 1,063 (word/name collisions)
                "HAIN", "HAO", "HAVA",
                # 2026-10-19 01:18 run (18-23Z), held by the guard: AUR 4,669 bare (own samples 2% real: the word/name
                # "aur"), DLA 4,575, MACI 2,595 (0%), MAA 2,163 (0%); AMAN and AURE: own samples ~0% real
                "AUR", "DLA", "MACI", "MAA", "AMAN", "AURE",
                # Applied Materials: "amat" is a common word (Indonesian/Malay "very"; own bare sample 2026-10-19 1/25
                # real). Ambiguous here, but re-admitted in config/context_tickers.txt (counted with a finance clause)
                "AMAT"}
# frequent in the corpus only because of the company / ticker itself
ALLOW = {"AMD", "MRNA", "IBM", "NVDA", "TSLA", "AAPL", "MSFT", "AMZN", "GOOGL", "GOOG",
         "PLTR", "INTC", "NFLX", "ORCL", "IREN", "WULF", "AAL", "RIVN", "HIMS"}


def classify(t):
    if len(t) <= 2:
        return "1-2 letters"
    if t in ALLOW:
        return None
    if t in MANUAL_EXTRA:
        return "manual (slang/acronym/common word)"
    low = t.lower()
    en = wordfreq.zipf_frequency(low, "en")
    if en >= EN_MIN:
        return "word en zipf %.1f" % en
    z, lang = max((wordfreq.zipf_frequency(low, l), l) for l in OTHER)
    if z >= OTHER_MIN:
        return "word %s zipf %.1f" % (lang, z)
    return None


def main():
    rows = list(csv.DictReader(open(os.path.join(ROOT, "data", "universe.csv"), encoding="utf-8")))
    # core tickers missing from the universe file (e.g. SHOP) are counted too, so they must be classified as well
    have = {r["ticker"] for r in rows}
    for line in open(os.path.join(ROOT, "config", "core_tickers.txt"), encoding="utf-8"):
        t = line.split("#")[0].strip().upper()
        if t and t not in have:
            rows.append({"ticker": t})
            have.add(t)
    out = []
    for r in rows:
        why = classify(r["ticker"])
        if why:
            out.append((r["ticker"], why))
    path = os.path.join(ROOT, "config", "ambiguous_tickers.txt")
    with open(path, "w", encoding="utf-8") as f:
        f.write("# GENERATED by scripts/gen_ambiguous.py (wordfreq %s) - do not edit by hand; change the rule there.\n"
                % getattr(wordfreq, "__version__", "?"))
        f.write("# Bare-ticker mode (since 2026-10-17): these tickers are common words / too short, so a bare search\n"
                "# cannot count them honestly. They are NOT measured (left out of groups and the ranking) unless\n"
                "# config/context_tickers.txt re-admits them with a finance-context clause. %d of %d tickers.\n"
                % (len(out), len(rows)))
        for t, why in out:
            f.write("%-6s # %s\n" % (t, why))
    print("%d ambiguous of %d -> %s" % (len(out), len(rows), os.path.relpath(path, ROOT)))


if __name__ == "__main__":
    sys.exit(main())
